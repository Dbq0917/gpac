/*
 * Regression for audio timeline discontinuities when splitting one source into
 * independent ISOBMFF files.
 *
 * At a split boundary the first packet of each stream only lands on that
 * stream's frame boundaries (audio frame size, video SAP). These generally do
 * not match the exact split point of the other streams, so after the first file
 * one stream starts slightly later than the other. The muxer used to translate
 * this offset into an empty edit list entry on every segment, re-introducing the
 * codec priming/boundary delay at each split and producing a growing gap when
 * the files are concatenated. The fix keeps every independent split file's
 * timelines starting at 0 instead of emitting a per-segment empty edit.
 *
 * The source filter synthesizes an AVC video PID and an AAC audio PID whose fixed
 * frame size (1024 samples) does not divide the 2 s split point (96000 audio
 * samples), which reliably triggers the boundary offset and the resulting empty
 * edit on the independent split files.
 */

